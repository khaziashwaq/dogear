/**
 * Generates supabase/seed.sql from the demo community, so a local or staging
 * Supabase project starts with the same sample readers as demo mode.
 *
 *   npm run db:seed:generate
 *
 * Demo accounts sign in with <username>@demo.dogear.app / dogear-demo.
 * Never run this seed against production.
 */
import { writeFileSync } from "node:fs";
import { buildSeed } from "../src/lib/data/demo/db";
import { DEMO_PASSWORD } from "../src/lib/data/seed/community";

const db = buildSeed();
const snake = (k: string) => k.replace(/[A-Z]/g, (m) => `_${m.toLowerCase()}`);
const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return `array[${v.map(lit).join(",")}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const rename: Record<string, Record<string, string>> = {
  profiles: { motif: "profile_motif" },
};
function insert(table: string, rows: object[], omit: string[] = []) {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]).filter((c) => !omit.includes(c));
  const names = cols.map((c) => rename[table]?.[c] ?? snake(c));
  const values = rows.map((r) => `(${cols.map((c) => lit((r as Record<string, unknown>)[c])).join(", ")})`).join(",\n  ");
  return `insert into public.${table} (${names.join(", ")}) values\n  ${values};\n\n`;
}

let sql = `-- Generated by scripts/generate-seed-sql.ts — do not edit by hand.\n-- Sample community for local development. Never run against production.\n\nbegin;\n\n`;
sql += `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)\nvalues\n  ${db.users
  .map((u) => `('00000000-0000-0000-0000-000000000000', '${u.id}', 'authenticated', 'authenticated', '${u.email}', extensions.crypt('${DEMO_PASSWORD}', extensions.gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '')`)
  .join(",\n  ")};\n\n`;
sql += `insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)\nvalues\n  ${db.users
  .map((u) => `(gen_random_uuid(), '${u.id}', '${u.id}', jsonb_build_object('sub', '${u.id}', 'email', '${u.email}'), 'email', now(), now(), now())`)
  .join(",\n  ")};\n\n`;
// Profiles are created by the auth trigger; fill them in.
for (const p of db.profiles) {
  sql += `update public.profiles set username = ${lit(p.username)}, display_name = ${lit(p.displayName)}, bio = ${lit(p.bio)}, pronouns = ${lit(p.pronouns)}, location = ${lit(p.location)}, accent = ${lit(p.accent)}, profile_motif = ${lit(p.motif)}, favourite_genres = ${lit(p.favouriteGenres)}, favourite_authors = ${lit(p.favouriteAuthors)}, reading_goal = ${lit(p.readingGoal)}, onboarded = true, created_at = ${lit(p.createdAt)} where id = '${p.id}';\n`;
}
sql += "\n";
sql += insert("books", db.books);
sql += insert("follows", db.follows);
sql += insert("user_books", db.userBooks);
sql += insert("reading_sessions", db.sessions);
sql += insert("reviews", db.reviews);
sql += insert("quotes", db.quotes);
sql += insert("lists", db.lists);
sql += insert("list_books", db.listBooks);
sql += insert("list_follows", db.listFollows);
// originals before reposts (FK)
sql += insert("posts", [...db.posts].sort((a, b) => Number(Boolean(a.repostOfId)) - Number(Boolean(b.repostOfId))));
sql += insert("comments", [...db.comments].sort((a, b) => Number(Boolean(a.parentId)) - Number(Boolean(b.parentId))));
sql += insert("likes", db.likes);
sql += insert("bookmarks", db.bookmarks);
sql += insert("recommendations", [...db.recommendations].sort((a, b) => Number(Boolean(a.parentId)) - Number(Boolean(b.parentId))));
sql += `-- Triggers generated notifications for the rows above; mirror demo read state.\nupdate public.notifications set read_at = created_at where created_at < now() - interval '3 days';\n\ncommit;\n`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`wrote supabase/seed.sql (${db.users.length} readers, ${db.books.length} books, ${db.posts.length} posts)`);
